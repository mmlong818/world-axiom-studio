function expandPrompt(payload) {
  const sectionTask = sectionTasks[payload.batch];
  if (!sectionTask) throw new Error('未知的世界之书部分。');
  return `本次阶段：继续编写世界之书。

【选定的世界概述】
${json(payload.seed)}

【材料事实底稿；还原模式只能沿用其中的明确事实，创造模式只把它当作用户硬约束】
${json(payload.sourceDossier)}

【已经完成的正文；必须继承其中的专名和事实】
${clip(payload.previous, 80_000) || '尚无正文'}

【本次写作范围】
${sectionTask}

用中文 Markdown，只输出可直接收入世界介绍的正文。采用现代白话，段落先说结论再给例子；不要连续堆叠专名，不要把要求转换成栏目清单。标题应帮助读者定位内容，不必追求古雅。不得输出创作说明、内部字段、来源标记、追溯标记、空栏目或代码围栏。`;
}

function lintPrompt(payload) {
  return `本次阶段：审阅完整世界之书，判断它是否具体、可读、可用且自洽。

【选定的世界概述】
${json(payload.seed)}

【材料事实底稿】
${json(payload.sourceDossier)}

【完整正文】
${clip(payload.world, 120_000)}

逐项检查：
- 第一次阅读的人能否先理解世界整体，再逐步接触细节；每部分开头是否先给出清楚结论；
- 语言是否是自然的现代白话；是否存在长句过多、抽象名词堆叠、古籍腔、报告腔或连续四字短语；
- 新专名首次出现时是否立即解释；普通段落是否一次引入超过三个新专名；
- 正文是否在介绍具体世界，而不是讲创作方法或罗列待填写栏目；
- 地点、居民、组织、物产、器物、习俗和历史遗痕是否有专名与可观察细节，但没有为了数量制造无用名称；
- 地理、资源、生态、历史、权力和普通生活之间是否互相支持；
- 普通人的居住、食物、工作、交易、出行、教育、治疗、礼法和现实危险是否能够回答；
- 条目是否只保留理解世界不可缺少的内容；能用正文一句话说明的内容是否被不必要地拆成条目；
- 每个条目是否回答“它是什么、在哪里或属于谁、为什么重要、与什么有关”，索引是否确实指向正文；
- 各部分是否沿用同一批专名和事实；
- 还原模式是否把材料明确、合理推断、说法冲突和尚无记载分开，是否出现无来源的专名或确定性陈述。

如果正文需要反复阅读才能理解，或大量句子同时塞入四项以上事实，至少判为 medium；如果主要章节都存在这种情况，判为 high。抽象原则冒充内容、方法语言过多、只有分类没有事实、条目琐碎泛滥、索引为空或生活无法落地，也属于 high。

只输出 JSON，不要代码围栏：
{
  "status":"通过|需修补",
  "score":0,
  "violations":[{"rule":"","location":"","problem":"","minimal_fix":"","severity":"high|medium|low"}],
  "structural_risks":[""],
  "untapped_potential":"",
  "passed_rules":[""]
}`;
}

