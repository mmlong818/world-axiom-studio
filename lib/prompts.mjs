const stageBuilders = {
  seeds: seedPrompt,
  expand: expandPrompt,
  lint: lintPrompt,
  repair: repairPrompt,
  summary: summaryPrompt,
};

export function buildPrompt(stage, payload) {
  const builder = stageBuilders[stage];
  if (!builder) throw new Error('未知的生成阶段。');
  return { system: SYSTEM, prompt: builder(payload ?? {}) };
}
